SELECT
date_format(Revenue_date,'%Y-%m') AS month,
    SUM(R.Amount) AS total_revenue
FROM Revenue r
JOIN Transactions t
    ON Revenue_id = t.transaction_id
JOIN Accounts a
    ON t.account_id = a.account_id
JOIN Customers c
    ON a.customer_id = c.customer_id
GROUP BY date_format(Revenue_date,'%Y-%m')
ORDER BY month;


SELECT
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    SUM(t.amount) AS total_deposits
FROM Customers c
JOIN Accounts a
    ON c.customer_id = a.customer_id
JOIN Transactions t
    ON a.account_id = t.account_id
WHERE t.transaction_type = 'Deposit'
GROUP BY c.customer_id, c.first_name, c.last_name
ORDER BY total_deposits DESC
LIMIT 5;

SELECT
    account_type,
    ROUND(AVG(Current_balance), 2) AS average_balance
FROM Accounts
GROUP BY account_type
ORDER BY average_balance DESC;

SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    COUNT(t.transaction_id) AS total_transactions
FROM Customers c
JOIN Accounts a
    ON c.customer_id = a.customer_id
JOIN Transactions t
    ON a.account_id = t.account_id
GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name
ORDER BY total_transactions DESC;

SELECT
    ROUND(
        SUM(CASE WHEN transaction_type = 'Deposit' THEN 1 ELSE 0 END) * 100.0 /
        COUNT(*),
        2
    ) AS deposit_percentage,
    ROUND(
        SUM(CASE WHEN transaction_type = 'Withdrawal' THEN 1 ELSE 0 END) * 100.0 /
        COUNT(*),
        2
    ) AS withdrawal_percentage
FROM Transactions
WHERE transaction_type IN ('Deposit', 'Withdrawal');

SELECT
    DATE_FORMAT(revenue_date, '%Y-%m') AS month,
    SUM(amount) AS total_revenue,
    SUM(amount) -
        LAG(SUM(amount)) OVER (ORDER BY DATE_FORMAT(revenue_date, '%Y-%m'))
        AS revenue_growth,
    ROUND(
        (
            (SUM(amount) -
             LAG(SUM(amount)) OVER (ORDER BY DATE_FORMAT(revenue_date, '%Y-%m')))
            /
            LAG(SUM(amount)) OVER (ORDER BY DATE_FORMAT(revenue_date, '%Y-%m'))
        ) * 100,
        2
    ) AS growth_percentage
FROM Revenue
GROUP BY DATE_FORMAT(revenue_date, '%Y-%m')
ORDER BY month;

SELECT
    revenue_source,
    SUM(amount) AS total_revenue,
    ROUND(
        SUM(amount) * 100.0 /
        (SELECT SUM(amount) FROM Revenue),
        2
    ) AS percentage_contribution
FROM Revenue
GROUP BY revenue_source
ORDER BY total_revenue DESC;

SELECT
    a.account_id,
    a.account_number,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    COUNT(t.transaction_id) AS transaction_count
FROM Accounts a
JOIN Customers c
    ON a.customer_id = c.customer_id
JOIN Transactions t
    ON a.account_id = t.account_id
GROUP BY
    a.account_id,
    a.account_number,
    c.first_name,
    c.last_name
ORDER BY transaction_count DESC
LIMIT 10;

